const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const release = require('../docs/release-data.js');
const docs = path.join(__dirname, '../target/site');
const html = fs.readFileSync(path.join(docs, 'index.html'), 'utf8');
for (const name of ['assets/clipvault.svg', 'history.png', 'style.css', 'site.js', 'theme.js', 'release-data.js']) assert(fs.existsSync(path.join(docs, name)), name);
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.equal(ids.length, new Set(ids).size, 'unique IDs');
for (const [, id] of html.matchAll(/href="#([^"]+)"/g)) assert(ids.includes(id), `missing anchor ${id}`);
assert(html.includes('<summary>') && html.includes('aria-label="Website theme"'));
assert(html.indexOf('src="theme.js"') < html.indexOf('href="style.css"'), 'theme before CSS');
assert(!/sudo apt (update|install clipvault)/.test(html), 'no invented APT repository');
assert(!/https?:.*tailwind.*(?:cdn|\.js)/.test(html), 'no Tailwind CDN');
const base = `${release.releases}/download/v2.2.0/`;
const asset = {name:'clipvault_2.2.0-1_amd64.deb', browser_download_url:base+'clipvault_2.2.0-1_amd64.deb', size:4000000};
const fixture = {tag_name:'v2.2.0', assets:[asset]};
assert.equal(release.parse(fixture).assets.deb.size, 4000000);
assert.equal(release.parse(fixture).assets.rpm, undefined);
for (const data of [{...fixture,draft:true},{...fixture,prerelease:true},{...fixture,tag_name:'v2.3.0-beta.1'}]) assert.throws(()=>release.parse(data));
for (const change of [{name:'other.deb'},{browser_download_url:'https://example.com/a.deb'},{browser_download_url:asset.browser_download_url.replace('v2.2.0/','v2.1.0/')},{name:'clipvault_2.2.0-1_arm64.deb'},{size:0},{state:'new'}]) assert.equal(release.parse({...fixture,assets:[{...asset,...change}]}).assets.deb, undefined);
console.log('Website static/release checks passed: build assets, anchors, theme initialization, exact architecture/name/version/URL, missing packages, drafts, prereleases and invalid sizes.');
const vm = require('node:vm');
const themeSource = fs.readFileSync(path.join(docs,'theme.js'),'utf8');
const siteSource = fs.readFileSync(path.join(docs,'site.js'),'utf8');
async function render(fail=false, initialTheme='dark', cache=null) {
  const saved = new Map([['clipvault-theme',initialTheme],['clipvault-release-cache',JSON.stringify(cache)]]);
  const root={dataset:{}};
  const selector={addEventListener:(_,callback)=>{selector.change=callback;}};
  const nodes={ '#theme':selector, '#release-status':{}, '#checksums':{}, '#release-notes-link':{} };
  const links=['deb','AppImage','rpm'].map(format=>({dataset:{format}, size:{},setAttribute(k,v){this[k]=v;},removeAttribute(k){delete this[k];},closest(){return{querySelector:()=>this.size};}}));
  const labels=[{}];
  const context={window:{ClipVaultRelease:release},document:{documentElement:root,querySelector:s=>nodes[s],querySelectorAll:s=>s==='[data-version]'?labels:links},localStorage:{getItem:k=>saved.get(k),setItem:(k,v)=>saved.set(k,v)},AbortSignal,Date,fetch:async()=>{if(fail)throw Error('offline');return{ok:true,json:async()=>fixture};}};
  vm.runInNewContext(themeSource,context);
  assert.equal(root.dataset.theme,['light','dark','system'].includes(initialTheme)?initialTheme:'system');
  await vm.runInNewContext(siteSource,context);
  await new Promise(resolve=>setImmediate(resolve));
  selector.change({target:{value:'light'}});
  assert.equal(saved.get('clipvault-theme'),'light');
  return{nodes,links,labels};
}
(async()=>{
  let result=await render();
  assert.equal(result.links[0].href,asset.browser_download_url);
  assert.equal(result.links[2].href,undefined);
  assert.equal(result.links[2]['aria-disabled'],'true');
  assert.equal(result.labels[0].textContent,'v2.2.0');
  result=await render(true,'invalid');
  assert(result.nodes['#release-status'].textContent.includes('unavailable'));
  assert(result.links.every(link=>!link.href));
  result=await render(true,'system',{checked:Date.now(),data:fixture});
  assert.equal(result.links[0].href,asset.browser_download_url);
  assert(result.nodes['#release-status'].textContent.includes('last 24 hours'));
  result=await render(true,'light',{checked:Date.now()-86400001,data:fixture});
  assert(result.links.every(link=>!link.href));
  console.log('Website DOM logic passed: remembered theme, invalid preference, missing assets, offline fallback, cache expiry, cached data disclosure. Browser rendering remains a separate check.');
})().catch(error=>{console.error(error);process.exitCode=1;});
