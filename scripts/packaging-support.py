#!/usr/bin/env python3
"""Offline, fail-closed notice generation and AppDir staging for Linux x86-64."""
import argparse
import hashlib
from html.parser import HTMLParser
import json
import pathlib
import re
import shutil
import struct
import subprocess
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
APPDIR = ROOT / "target/packaging/ClipVault.AppDir"
DOC = APPDIR / "usr/share/doc/clipvault"
HOST_LIBRARIES = {
    "libc.so.6", "libm.so.6", "libmvec.so.1", "libdl.so.2", "libpthread.so.0",
    "librt.so.1", "libresolv.so.2", "libutil.so.1", "libanl.so.1", "libgcc_s.so.1",
}


def host_library(name):
    return name in HOST_LIBRARIES or name.startswith(("ld-linux-", "libGL", "libEGL", "libOpenGL", "libdrm", "libgbm", "libnss_"))


def run(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def font_notices(path):
    """Read attribution/license names directly from the shipped sfnt font."""
    raw = path.read_bytes()
    count = struct.unpack_from(">H", raw, 4)[0]
    for i in range(count):
        tag, _, offset, _ = struct.unpack_from(">4sIII", raw, 12 + i * 16)
        if tag != b"name":
            continue
        _, n, strings = struct.unpack_from(">HHH", raw, offset)
        texts = set()
        for j in range(n):
            platform, _, _, name, length, start = struct.unpack_from(">HHHHHH", raw, offset + 6 + j * 12)
            if name in {0, 7, 13, 14}:
                data = raw[offset + strings + start:offset + strings + start + length]
                texts.add(data.decode("utf-16-be" if platform in {0, 3} else "mac_roman"))
        return "\n".join(sorted(texts))
    raise RuntimeError(f"Font has no attribution table: {path}")


def notices(check):
    metadata = json.loads(run("cargo", "metadata", "--format-version", "1", "--locked", "--offline", "--filter-platform", "x86_64-unknown-linux-gnu"))
    # Unlike metadata's resolve graph, cargo tree excludes disabled optional features.
    tree = run("cargo", "tree", "--locked", "--offline", "--target", "x86_64-unknown-linux-gnu", "--edges", "normal,build", "--prefix", "none", "--format", "{p}")
    active = {line.split(" (")[0] for line in tree.splitlines()}
    chunks = ["ClipVault third-party notices\nGenerated by scripts/packaging-support.py notices from Cargo.lock and the active Linux dependency graph.\nBuild dependencies are included conservatively. Original component licenses apply.\n"]
    count = 0
    egui = {"ecolor", "eframe", "egui", "egui-winit", "egui_glow", "emath", "epaint", "epaint_default_fonts"}
    for package in sorted(metadata["packages"], key=lambda p: (p["name"], p["version"])):
        name, version = package["name"], package["version"]
        if name == "clipvault" or f"{name} v{version}" not in active:
            continue
        count += 1
        source = pathlib.Path(package["manifest_path"]).parent
        chunks.append(f"\n{'=' * 72}\n{name} {version}\nSPDX: {package['license']}\nSource: {package.get('repository') or package.get('source')}\nAuthors: {', '.join(package['authors'])}\n")
        files = []
        for p in sorted(source.rglob("*")):
            lower = p.name.lower()
            if p.is_file() and (lower.startswith(("license", "licence", "copying", "copyright", "notice")) or "license" in lower or ("fonts" in p.parts and p.suffix == ".txt")):
                files.append((str(p.relative_to(source)), p.read_text()))
        if name in egui and version == "0.31.1":
            files.append(("upstream LICENSE-MIT (packaging/licenses/egui-MIT.txt)", (ROOT / "packaging/licenses/egui-MIT.txt").read_text()))
        if name == "profiling" and version == "1.0.18":
            files.append(("upstream LICENSE-MIT (packaging/licenses/profiling-MIT.txt)", (ROOT / "packaging/licenses/profiling-MIT.txt").read_text()))
        if name in {"gl_generator", "khronos_api"} and version in {"0.14.0", "3.1.0"}:
            files.append(("Apache-2.0", (ROOT / "packaging/licenses/Apache-2.0.txt").read_text()))
            if name == "gl_generator":
                files.append(("lib.rs copyright header", (source / "lib.rs").read_text().split("//!", 1)[0]))
            else:
                for xml in sorted(source.rglob("*.xml")):
                    match = re.search(r"<comment>(.*?)</comment>", xml.read_text(), re.S)
                    if match:
                        files.append((str(xml.relative_to(source)) + " registry notice", match.group(1)))
        if not files:
            raise RuntimeError(f"Missing license text: {name} {version}; add a version-specific upstream license")
        for label, content in files:
            chunks.append(f"\n--- {label} ---\n{content.rstrip()}\n")
        # Only egui's embedded fonts are shipped; dependency test fonts are not.
        for font in sorted((source / "fonts").glob("*.ttf")) if name == "epaint_default_fonts" else []:
            chunks.append(f"\n--- {font.name} embedded attribution ---\n{font_notices(font)}\n")
    chunks.append("\n" + "=" * 72 + "\nBundled Bootstrap social icons\n" + (ROOT / "assets/social/LICENSE.txt").read_text())
    chunks.append("\n" + "=" * 72 + "\nassets/Interface.ttf (Noto Sans Regular)\n" + font_notices(ROOT / "assets/Interface.ttf") + "\n" + (ROOT / "assets/Interface.ttf.LICENSE").read_text())
    # Rust's linked standard library has dependencies outside Cargo.lock.
    class RustNotices(HTMLParser):
        def handle_data(self, data):
            chunks.append(data)

    rust_notices = pathlib.Path(run("rustc", "--print", "sysroot")) / "share/doc/rust/COPYRIGHT-library.html"
    chunks.append("\n" + "=" * 72 + "\nRust standard library: " + run("rustc", "--version") + "\nComplete standard-library notices from the installed toolchain follow, including other-platform components conservatively.\n")
    RustNotices().feed(rust_notices.read_text())
    result = "".join(chunks)
    path = ROOT / "THIRD-PARTY-NOTICES.txt"
    if check:
        if not path.exists() or path.read_text() != result:
            raise RuntimeError("THIRD-PARTY-NOTICES.txt is stale; run python3 scripts/packaging-support.py notices")
    else:
        path.write_text(result)
    print(f"Verified notices for {count} active Rust dependencies and embedded fonts" if check else f"Generated notices for {count} active Rust dependencies and embedded fonts")


def library_paths():
    paths = {}
    for line in run("/sbin/ldconfig", "-p").splitlines():
        match = re.match(r"\s*(\S+) \(.*x86-64.*\) => (.*)", line)
        if match:
            paths.setdefault(match[1], pathlib.Path(match[2]))
    return paths


def stage():
    # This fixed generated directory is safe to rebuild. No user data is copied.
    if APPDIR.exists():
        shutil.rmtree(APPDIR)
    sources = {}

    def copy(source, relative):
        source = pathlib.Path(source)
        dest = APPDIR / relative
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, dest)
        sources[str(relative)] = str(source.resolve())

    copy(ROOT / "target/release/clipvault", "usr/bin/clipvault")
    copy(ROOT / "packaging/linux/AppRun", "AppRun")
    (APPDIR / "AppRun").chmod(0o755)
    desktop = "io.clipvault.desktop.desktop"
    copy(ROOT / "packaging/linux" / desktop, "usr/share/applications/" + desktop)
    (APPDIR / desktop).symlink_to("usr/share/applications/" + desktop)
    copy(ROOT / "assets/clipvault.svg", "usr/share/icons/hicolor/scalable/apps/clipvault.svg")
    for size in (16,24,32,48,64,128,256,512):
        copy(ROOT / f"assets/icons/{size}x{size}/clipvault.png", f"usr/share/icons/hicolor/{size}x{size}/apps/clipvault.png")
    (APPDIR / "clipvault.svg").symlink_to("usr/share/icons/hicolor/scalable/apps/clipvault.svg")
    (APPDIR / ".DirIcon").symlink_to("clipvault.svg")
    for name in ["LICENSE", "THIRD-PARTY-NOTICES.txt", "README.md", "RELEASE-NOTES.md", "VERIFICATION.md", "ACTIVATION-VERIFICATION.md", "FEATURE-VERIFICATION.md"]:
        copy(ROOT / name, "usr/share/doc/clipvault/" + name)
    copy(ROOT / "packaging/README.md", "usr/share/doc/clipvault/PACKAGING.md")
    copy(ROOT / "packaging/SOFTWARE-MANAGER-VERIFICATION.md", "usr/share/doc/clipvault/SOFTWARE-MANAGER-VERIFICATION.md")
    copy(ROOT / "docs/history.png", "usr/share/doc/clipvault/docs/history.png")
    copy(ROOT / "assets/clipvault.svg", "usr/share/doc/clipvault/assets/clipvault.svg")
    paths = library_paths()
    for line in (ROOT / "packaging/linux/runtime-libraries.txt").read_text().splitlines():
        if line and not line.startswith("#"):
            copy(paths[line], "usr/lib/" + line)
    pixbuf = pathlib.Path("/usr/lib/x86_64-linux-gnu/gdk-pixbuf-2.0")
    copy(pixbuf / "gdk-pixbuf-query-loaders", "usr/bin/gdk-pixbuf-query-loaders")
    # Ship the GIF and WebP loaders actually used; avoid unrelated SVG/HEIF stacks.
    for name in ["libpixbufloader-gif.so", "libpixbufloader-webp.so"]:
        copy(pixbuf / "2.10.0/loaders" / name, "usr/lib/gdk-pixbuf-2.0/2.10.0/loaders/" + name)
    # Force the entire non-host closure, including desktop libraries normally
    # excluded by linuxdeploy. linuxdeploy will adjust ELF paths when available.
    queue = [APPDIR / name for name in sources]
    visited = set()
    while queue:
        elf = queue.pop()
        if elf in visited or elf.read_bytes()[:4] != b"\x7fELF":
            continue
        visited.add(elf)
        linkage = run("ldd", str(elf))
        if "not found" in linkage:
            raise RuntimeError(f"Missing runtime dependency of {elf}: {linkage}")
        for name, location in re.findall(r"^\s*(\S+) => (/.*?) \(", linkage, re.M):
            if host_library(name):
                continue
            relative = "usr/lib/" + name
            if relative not in sources:
                copy(location, relative)
                queue.append(APPDIR / relative)
    (APPDIR.parent / "staged-sources.json").write_text(json.dumps(sources, indent=2) + "\n")
    print(f"Staged {APPDIR}; ELF path adjustments and AppImage creation still require linuxdeploy")


def verify_closure():
    for elf in APPDIR.rglob("*"):
        if not elf.is_file() or elf.is_symlink() or elf.read_bytes()[:4] != b"\x7fELF":
            continue
        linkage = run("ldd", str(elf))
        if "not found" in linkage:
            raise RuntimeError(f"Missing ELF dependency of {elf}: {linkage}")
        for name, location in re.findall(r"^\s*(\S+) => (/.*?) \(", linkage, re.M):
            if not host_library(name) and not pathlib.Path(location).resolve().is_relative_to(APPDIR.resolve()):
                raise RuntimeError(f"Unbundled dependency {name} loaded from {location}")
    print("Verified non-host library closure (glibc, libgcc and graphics dispatch remain on the host)")


def system_notices():
    sources = json.loads((APPDIR.parent / "staged-sources.json").read_text())
    paths = library_paths()
    packages = {}
    for f in sorted(APPDIR.rglob("*")):
        if not f.is_file() or f.is_symlink() or f.read_bytes()[:4] != b"\x7fELF":
            continue
        relative = str(f.relative_to(APPDIR))
        if relative == "usr/bin/clipvault":
            continue
        source = sources.get(relative) or paths.get(f.name)
        if not source:
            # linuxdeploy copies resolved filenames as well as SONAME aliases.
            # ldconfig indexes the SONAME, so resolve known host paths before
            # looking up Debian ownership; reject ambiguous mappings.
            matches = {str(pathlib.Path(p).resolve()) for p in [*sources.values(), *paths.values()]
                       if pathlib.Path(p).resolve().name == f.name}
            if len(matches) == 1:
                source = matches.pop()
        if not source:
            raise RuntimeError(f"Unknown source for bundled ELF: {relative}")
        source = pathlib.Path(source).resolve()
        candidates = [str(source), str(source).removeprefix("/usr")]
        owner = None
        for candidate in candidates:
            result = subprocess.run(["dpkg-query", "-S", candidate], text=True, capture_output=True)
            if result.returncode == 0:
                owner = result.stdout.split(": ", 1)[0]
                break
        if not owner:
            raise RuntimeError(f"No Debian source/copyright information for {source}")
        package = owner.split(":")[0]
        dest = DOC / "system-libraries" / package
        dest.mkdir(parents=True, exist_ok=True)
        shutil.copy2(pathlib.Path("/usr/share/doc") / package / "copyright", dest / "copyright")
        info = run("dpkg-query", "-W", "-f=${binary:Package}\t${Version}\t${source:Package}\t${source:Version}", owner)
        packages[info] = packages.get(info, []) + [relative]
    common = DOC / "system-libraries/common-licenses"
    shutil.copytree("/usr/share/common-licenses", common, symlinks=False, dirs_exist_ok=True)
    manifest = ["Bundled distribution libraries (unmodified upstream code; linuxdeploy may adjust ELF paths).", "Fields: binary package, binary version, source package, source version; followed by bundled paths.", "Matching source: enable Ubuntu noble deb-src repositories and run apt-get source SOURCE=SOURCE_VERSION.", "Source archive: https://archive.ubuntu.com/ubuntu/pool/ (or https://security.ubuntu.com/ubuntu/pool/).", "Library copyright files and complete common license texts accompany this manifest.", "Extract with --appimage-extract to replace shared libraries and run squashfs-root/AppRun.", "Core glibc, host OpenGL/EGL and GPU drivers are not bundled.", ""]
    for info, files in sorted(packages.items()):
        manifest.extend([info, *["  " + f for f in files], ""])
    (DOC / "SYSTEM-LIBRARY-SOURCES.txt").write_text("\n".join(manifest))
    (DOC / "BUILD-INFO.txt").write_text(run("rustc", "--version") + "\n" + run("cargo", "--version") + "\n" + pathlib.Path("/etc/os-release").read_text() + "Cargo.lock SHA256: " + hashlib.sha256((ROOT / "Cargo.lock").read_bytes()).hexdigest() + "\n")
    print(f"Collected copyright and source metadata for {len(packages)} system library packages")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["notices", "stage", "system-notices", "verify-closure"])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        {"notices": lambda: notices(args.check), "stage": stage, "system-notices": system_notices, "verify-closure": verify_closure}[args.action]()
    except (RuntimeError, KeyError, FileNotFoundError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Packaging failed: {error}\n")
